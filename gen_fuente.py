ORDEN = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ :-!.#*"
assert all(len(g) == 7 and all(len(r) == 5 for r in g) for g in G.values())

lineas = []
for code, ch in enumerate(ORDEN):
    for fila, bits in enumerate(G[ch]):
        lineas.append(f'            when {code * 8 + fila} => bits <= "{bits}";   -- \'{ch}\' fila {fila}')

